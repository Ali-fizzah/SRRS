"""Generate docs/erd.md (a mermaid ER diagram) from the SQLAlchemy models (plan §3).

Run from backend/ so `app` is importable:
    python ../tools/gen_erd.py ../docs/erd.md
`make erd` does this. A unit test fails if docs/erd.md is out of date.
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))

from sqlalchemy import Column, Table  # noqa: E402
from sqlalchemy.dialects import postgresql  # noqa: E402

import app.models  # noqa: E402, F401  (registers every table)
from app.db.base import Base  # noqa: E402

# Tables grouped as in plan §6.1, in that order.
GROUPS = {
    "Master data": ["customers", "products", "ssp_rules", "gl_accounts", "gl_mappings"],
    "Contracts": [
        "contracts",
        "contract_versions",
        "contract_lines",
        "performance_obligations",
        "deliveries",
    ],
    "Billing": ["invoices", "invoice_lines", "credit_notes"],
    "Revenue": ["revenue_schedules", "schedule_lines"],
    "Ledger": ["accounting_periods", "journal_batches", "journal_entries", "journal_lines"],
    "Control": [
        "upload_files",
        "validation_errors",
        "job_runs",
        "audit_log",
        "users",
        "roles",
        "user_roles",
    ],
}

SRC_COLUMNS = {"source_upload_id", "source_row", "source_payload"}


def _type(col: Column) -> str:  # type: ignore[type-arg]
    rendered = str(col.type.compile(dialect=postgresql.dialect())).lower()
    rendered = rendered.replace("timestamp with time zone", "timestamptz")
    return re.sub(r"[^a-z0-9]+", "_", rendered).strip("_")


def _keys(col: Column) -> str:  # type: ignore[type-arg]
    keys = []
    if col.primary_key:
        keys.append("PK")
    if col.foreign_keys:
        keys.append("FK")
    if col.unique:
        keys.append("UK")
    return ",".join(keys)


def _entity(table: Table) -> list[str]:
    lines = [f"    {table.name} {{"]
    for col in table.columns:
        if col.name in SRC_COLUMNS or col.name == "created_at":
            continue
        keys = _keys(col)
        null = "" if col.nullable is False else ' "nullable"'
        lines.append(f"        {_type(col)} {col.name}{' ' + keys if keys else ''}{null}")
    lines.append("    }")
    return lines


def _relationships(table: Table) -> list[str]:
    lines = []
    for col in table.columns:
        for fk in col.foreign_keys:
            target = fk.column.table.name
            many = "}o" if not col.unique else "|o"
            one = "o|" if col.nullable else "||"
            lines.append(f"    {table.name} {many}--{one} {target} : {col.name}")
    return lines


def render() -> str:
    tables = Base.metadata.tables
    grouped = [name for names in GROUPS.values() for name in names]
    missing = set(tables) - set(grouped)
    if missing:
        raise SystemExit(f"tables not assigned to a group in gen_erd.py: {sorted(missing)}")

    out = [
        "# Entity-relationship diagram",
        "",
        "<!-- Generated by tools/gen_erd.py from backend/app/models. Do not edit by hand; "
        "run `make erd`. -->",
        "",
        "Schema from plan §6.1. Every table also has `created_at`. Tables marked *(src)* also",
        "keep `source_upload_id → upload_files`, `source_row` and `source_payload` (CLAUDE.md",
        "rule 5); those columns and their links to `upload_files` are left out of the diagram",
        "to keep it readable.",
        "",
    ]
    for group, names in GROUPS.items():
        marked = [f"`{n}`" + (" *(src)*" if "source_payload" in tables[n].c else "") for n in names]
        out.append(f"- **{group}:** " + ", ".join(marked))
    out += ["", "```mermaid", "erDiagram"]
    for name in grouped:
        out += _entity(tables[name])
    out.append("")
    for name in grouped:
        rels = [r for r in _relationships(tables[name]) if not r.endswith(": source_upload_id")]
        out += rels
    out += ["```", ""]
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    Path(sys.argv[1]).write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {sys.argv[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
