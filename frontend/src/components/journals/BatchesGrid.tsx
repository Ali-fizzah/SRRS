"use client";

import Box from "@mui/material/Box";
import Button from "@mui/material/Button";
import Link from "@mui/material/Link";
import type { GridColDef } from "@mui/x-data-grid";
import NextLink from "next/link";

import BatchStatusChip from "@/components/journals/BatchStatusChip";
import ServerDataGrid from "@/components/ServerDataGrid";
import type { Schemas } from "@/lib/api/client";
import { formatMoney, formatPeriod } from "@/lib/format";

type Batch = Schemas["JournalBatchOut"];

const money = (value: string) => formatMoney(value);

const COLUMNS: GridColDef<Batch>[] = [
  {
    field: "period_key",
    headerName: "Period",
    width: 110,
    valueFormatter: (value: string) => formatPeriod(value),
  },
  {
    field: "batch_no",
    headerName: "Batch",
    width: 90,
    renderCell: ({ row }) => (
      <Link component={NextLink} href={`/journals/${row.id}`}>
        Batch {row.batch_no}
      </Link>
    ),
  },
  {
    field: "status",
    headerName: "Status",
    width: 120,
    renderCell: ({ row }) => <BatchStatusChip status={row.status} />,
  },
  { field: "entry_count", headerName: "Entries", type: "number", width: 90, sortable: false },
  {
    field: "total_debit",
    headerName: "Debit",
    width: 130,
    align: "right",
    headerAlign: "right",
    valueFormatter: money,
  },
  {
    field: "total_credit",
    headerName: "Credit",
    width: 130,
    align: "right",
    headerAlign: "right",
    valueFormatter: money,
  },
  {
    field: "generated_by_name",
    headerName: "Generated by",
    flex: 1,
    minWidth: 140,
    sortable: false,
  },
  {
    field: "approved_by_name",
    headerName: "Approved by",
    flex: 1,
    minWidth: 140,
    sortable: false,
  },
  { field: "posted_by_name", headerName: "Posted by", flex: 1, minWidth: 140, sortable: false },
];

/** Journal batches by period and status, newest first (plan §9). */
export default function BatchesGrid() {
  return (
    <ServerDataGrid<Batch>
      path="/journal-batches"
      columns={COLUMNS}
      label="Journal batches"
      emptyText="No journal batches yet. Generate one for the current period."
      renderSummary={() => (
        <Box sx={{ display: "flex", justifyContent: "flex-end" }}>
          <Button variant="outlined" size="small" href="/api/v1/journal-batches?format=csv">
            Export CSV
          </Button>
        </Box>
      )}
    />
  );
}
